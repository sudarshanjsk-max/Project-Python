# typecasting is the process of converting a variable from one data type to another.
# In Python, you can use built-in functions like int(), float(), str(), etc. to perform type casting.

name='Sudarshan'
age=14
gpa=3.9
is_student=True

# type casting
print(type(age))
print(type(gpa))
print(type(is_student))

# how to change values using type casting
gpa=int(gpa)
print(gpa)
age=float(age)
print(age)
